#!/usr/bin/env python3
"""Generate the Kiln GtkSourceView 5 style schemes (kiln, kiln-dark) into OUTDIR."""
import sys, os
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
L = dict(id='kiln', name='Kiln', bg='#FAF9F5', fg='#2B2926', cur='#F2EEE3', ln_fg='#9A9384', ln_bg='#FAF9F5', sel='#F2D5C6',
         comment='#8A8374', string='#4F7A4F', kw='#B5502C', typ='#3E6A94', num='#9A6F10', const='#8A4F7D', pre='#2F7F7A',
         fn='#3E6A94', err='#B03A2E', match='#F2D5C6', bracket='#E8D9C5', variant='light')
D = dict(id='kiln-dark', name='Kiln Dark', bg='#24221F', fg='#F3EFE6', cur='#2B2926', ln_fg='#6B665C', ln_bg='#2B2926', sel='#584035',
         comment='#8A8374', string='#8DB58A', kw='#E38A6C', typ='#7FA8CF', num='#E0B04F', const='#C58BB9', pre='#6FBDB6',
         fn='#9BBFE0', err='#EE8A7C', match='#584035', bracket='#4A4640', variant='dark')
T = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Kiln GNU/Linux flat paper style scheme ({name}); generated by tools/gen-sourceview.py -->
<style-scheme id="{id}" name="{name}" version="1.0">
  <metadata><property name="variant">{variant}</property></metadata>
  <style name="text" foreground="{fg}" background="{bg}"/>
  <style name="selection" background="{sel}"/>
  <style name="current-line" background="{cur}"/>
  <style name="current-line-number" foreground="{fg}" background="{ln_bg}" bold="true"/>
  <style name="line-numbers" foreground="{ln_fg}" background="{ln_bg}"/>
  <style name="cursor" foreground="#D97757"/>
  <style name="draw-spaces" foreground="{ln_fg}"/>
  <style name="right-margin" foreground="{ln_fg}"/>
  <style name="search-match" background="{match}"/>
  <style name="bracket-match" background="{bracket}" bold="true"/>
  <style name="bracket-mismatch" foreground="{err}" underline="true"/>
  <style name="def:comment" foreground="{comment}" italic="true"/>
  <style name="def:shebang" foreground="{comment}" bold="true"/>
  <style name="def:doc-comment-element" foreground="{comment}" italic="true"/>
  <style name="def:string" foreground="{string}"/>
  <style name="def:character" foreground="{string}"/>
  <style name="def:special-char" foreground="{pre}"/>
  <style name="def:keyword" foreground="{kw}"/>
  <style name="def:statement" foreground="{kw}"/>
  <style name="def:type" foreground="{typ}"/>
  <style name="def:function" foreground="{fn}"/>
  <style name="def:builtin" foreground="{fn}"/>
  <style name="def:number" foreground="{num}"/>
  <style name="def:constant" foreground="{const}"/>
  <style name="def:boolean" foreground="{const}"/>
  <style name="def:preprocessor" foreground="{pre}"/>
  <style name="def:identifier" foreground="{fg}"/>
  <style name="def:error" foreground="{err}" underline="true"/>
  <style name="def:warning" underline="true" foreground="{num}"/>
  <style name="def:note" foreground="{fg}" background="{sel}"/>
  <style name="def:link-destination" foreground="{typ}" underline="true"/>
  <style name="def:heading" foreground="{kw}" bold="true"/>
  <style name="def:emphasis" italic="true"/>
  <style name="def:strong-emphasis" bold="true"/>
  <style name="def:inline-code" foreground="{pre}"/>
  <style name="def:added-line" foreground="{string}"/>
  <style name="def:removed-line" foreground="{err}"/>
  <style name="def:changed-line" foreground="{num}"/>
</style-scheme>
'''
for s in (L, D):
    open(os.path.join(out, s['id'] + '.xml'), 'w').write(T.format(**s))
