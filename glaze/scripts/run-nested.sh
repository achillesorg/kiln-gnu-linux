#!/usr/bin/env bash
#
# Glaze — run the shell nested (developer mode, non-destructive).
#
# Default behaviour: start a NESTED wlroots compositor (Sway) inside a window of
# your current session and launch `glaze-shell` inside it. The host session is
# never modified: no login manager is touched, no system configuration is
# written, and the nested compositor uses its own Wayland socket. When the
# nested compositor exits, everything it started goes with it.
#
# Usage:
#   scripts/run-nested.sh [--windowed] [--x11] [--headless]
#                         [--use-current] [--compositor sway] [--help]

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

MODE="nested"          # nested | current
BACKEND="wayland"      # wayland | x11 | headless  (nested compositor backend)
COMPOSITOR="sway"
SHELL_BIN=""

usage() {
    cat <<'EOF'
run-nested.sh — start Glaze nested, without touching the host session

USAGE:
    scripts/run-nested.sh [OPTIONS]

MODES:
    (default)        Start a nested compositor in a window and run glaze-shell.
    --windowed       Run the nested compositor in a window (default on Wayland).
    --x11            Nest the compositor on the host X11 (XWayland) display.
    --headless       Use the headless backend (no window; for smoke tests).
    --use-current    Do NOT start a compositor; launch glaze-shell inside the
                     current wlroots session. This is the only mode that places
                     the panel on your real desktop, so it is opt-in.

OPTIONS:
    --compositor N   Nested compositor to use (default: sway).
    -h, --help       Show this help.

SAFETY:
    * Never edits the login manager, boot configuration, or other sessions.
    * The nested compositor uses its own runtime socket; the host is untouched.
    * Temporary configuration is created under a mktemp directory and removed
      on exit.
EOF
}

log()  { printf '\033[1;34m[glaze]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[glaze]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[glaze]\033[0m %s\n' "$*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
    case "$1" in
        --windowed) BACKEND="wayland" ;;
        --x11)      BACKEND="x11" ;;
        --headless) BACKEND="headless" ;;
        --use-current) MODE="current" ;;
        --compositor) shift || true; COMPOSITOR="${1:-}"; [[ -n "$COMPOSITOR" ]] || die "--compositor needs a value" ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown argument: $1 (try --help)" ;;
    esac
    shift
done

# --- resolve how to launch glaze-shell --------------------------------------

resolve_shell() {
    local candidate
    for candidate in \
        "$ROOT/target/release/glaze-shell" \
        "$ROOT/target/debug/glaze-shell" \
        "$ROOT/apps/glaze-shell/target/release/glaze-shell" \
        "$ROOT/apps/glaze-shell/target/debug/glaze-shell"
    do
        if [[ -x "$candidate" ]]; then
            SHELL_BIN="$candidate"
            return 0
        fi
    done
    if command -v glaze-shell >/dev/null 2>&1; then
        SHELL_BIN="$(command -v glaze-shell)"
        return 0
    fi
    return 1
}

if ! resolve_shell; then
    die "glaze-shell not found. Build it first (scripts/build.sh) on Fedora, then re-run."
fi
log "glaze-shell: $SHELL_BIN"

# --- host display detection -------------------------------------------------

HOST_WAYLAND=0
HOST_X11=0
[[ -n "${WAYLAND_DISPLAY:-}" ]] && HOST_WAYLAND=1
[[ -n "${DISPLAY:-}" ]] && HOST_X11=1

if [[ "$MODE" == "nested" ]]; then
    if [[ "$BACKEND" == "wayland" && "$HOST_WAYLAND" -eq 0 ]]; then
        if [[ "$HOST_X11" -eq 1 ]]; then
            warn "no Wayland display; falling back to the X11 backend."
            BACKEND="x11"
        else
            die "no WAYLAND_DISPLAY or DISPLAY set; cannot run nested."
        fi
    fi

    if ! command -v "$COMPOSITOR" >/dev/null 2>&1; then
        die "'$COMPOSITOR' not found. Install it (Fedora: sudo dnf install sway) or pass --use-current."
    fi

    tmpdir="$(mktemp -d "${TMPDIR:-/tmp}/glaze-nested.XXXXXX")"
    cleanup() { rm -rf "$tmpdir"; }
    trap cleanup EXIT

    cfg="$tmpdir/sway-nested.conf"
    cat >"$cfg" <<EOF
# Generated by scripts/run-nested.sh — a throwaway nested session.
# It never replaces or edits your real compositor configuration.
xwayland disable
exec $SHELL_BIN
EOF

    log "this will start a NESTED '$COMPOSITOR' (backend: $BACKEND) inside a"
    log "window of your current session, then exec: $SHELL_BIN"
    log "your host session is NOT modified; closing the nested window ends it."
    # Sway refuses to start on software rendering unless told it is expected.
    extra_args=()
    if [[ "$COMPOSITOR" == "sway" ]]; then
        extra_args+=("--unsupported-gpu")
    fi

    log "exact command:"
    printf '    WLR_BACKENDS=%s WLR_LIBINPUT_NO_DEVICES=1 XDG_CURRENT_DESKTOP=Glaze \\\n' "$BACKEND"
    printf '        %s %s -c %s\n' "$COMPOSITOR" "${extra_args[*]:-}" "$cfg"

    export WLR_BACKENDS="$BACKEND"
    export WLR_LIBINPUT_NO_DEVICES=1
    export XDG_CURRENT_DESKTOP="Glaze"
    # Software rendering is the safe default in a nested window.
    : "${WLR_RENDERER:=}"
    if [[ -n "$WLR_RENDERER" ]]; then
        export WLR_RENDERER
    fi

    exec "$COMPOSITOR" ${extra_args[@]+"${extra_args[@]}"} -c "$cfg"
fi

# --- --use-current: run the shell in the existing session -------------------

if [[ "$HOST_WAYLAND" -eq 0 ]]; then
    die "no WAYLAND_DISPLAY set; glaze-shell needs a Wayland session."
fi

warn "--use-current places the Glaze panel on your CURRENT desktop."
warn "it starts only glaze-shell (no compositor, no login manager changes)."

export XDG_CURRENT_DESKTOP="Glaze"

if [[ -n "${SWAYSOCK:-}" ]] && command -v swaymsg >/dev/null 2>&1; then
    log "current compositor is Sway; asking it to launch the shell:"
    printf '    swaymsg -t command exec %s\n' "$SHELL_BIN"
    exec swaymsg -t command exec "$SHELL_BIN"
fi

log "launching glaze-shell directly on the current Wayland session:"
printf '    %s\n' "$SHELL_BIN"
exec "$SHELL_BIN"
