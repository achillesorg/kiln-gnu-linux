#!/usr/bin/env python3
"""Generate the Kiln GNU/Linux Plymouth boot themes (original artwork, MIT OR Apache-2.0).

    python3 packaging/kilnlinux/plymouth/gen_plymouth.py

Writes, next to this script:
    kiln/          script theme, dark   (kiln.plymouth + kiln.script + PNG pieces)
    kiln-light/    script theme, light
    kiln-frames/   two-step fallback, dark  (pre-rendered PNG frames, no script support needed)
    kiln-frames-light/  two-step fallback, light
    preview/       contact strip of sampled frames (for review only, not installed)
and in ~/fedeos/brand/kiln/:
    kiln-boot-animated-dark.svg / -light.svg   SMIL preview of the same motion (no JS)

The motion (identical in all three forms, from one TIMELINE below):
  0.00-0.70 s  outer terracotta arch slides up 36 px and fades in (ease-out-back, small settle)
  0.22-0.95 s  inner arch slides up 56 px and fades in (same easing, later = paper layer on top)
  0.95 s ...   calm loop: the arch's counter glows like an ember (opacity 0.10..0.55, 2.8 s period,
               sine), the progress bar eases toward the real boot progress
  quit         everything fades out over 0.35 s so the greeter can take over
Reduced motion: set `reduced_motion = 1;` at the top of kiln.script (the generator
flag --reduced-motion bakes it in): arches appear in place, no ember pulse,
the progress bar still moves (it carries information).

Needs rsvg-convert. Stdlib only. Nothing here installs anything.
"""
import argparse
import math
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BRAND = os.path.expanduser("~/fedeos/brand/kiln")

TERRA, INK, CREAM, CHAR = "#D97757", "#2B2926", "#FAF9F5", "#1F1E1C"
OUTER = "M28 228V120a100 100 0 0 1 200 0v108zM60 228V120a68 68 0 0 1 136 0v108z"
INNER = "M82 228V124a46 46 0 0 1 92 0v104zM110 228V128a18 18 0 0 1 36 0v100z"
EMBER = "M110 228V128a18 18 0 0 1 36 0v100z"

SCHEMES = {
    #        background, inner arch, track,     text
    "dark": (CHAR, CREAM, "#3A3733", "#CFC7BA"),
    "light": (CREAM, INK, "#E4DCCB", "#5A534B"),
}

# ---- one timeline, used by the Python frame renderer, the script and the SVG ---
FPS = 50                 # Plymouth calls the refresh function about 50 times a second
OUTER_T = (0.00, 0.70)   # start, end (s)
INNER_T = (0.22, 0.95)
OUTER_DY, INNER_DY = 36, 56  # px at a 1080 px tall screen (scaled with the logo)
EMBER_PERIOD = 2.8
EMBER_MIN, EMBER_MAX = 0.10, 0.55
FADE_OUT = 0.35
BACK = 0.9               # ease-out-back overshoot (small: a settle, not a bounce)


def ease_out_back(t):
    t = min(max(t, 0.0), 1.0)
    c1, c3 = BACK, BACK + 1
    return 1 + c3 * (t - 1) ** 3 + c1 * (t - 1) ** 2


def ease_out_cubic(t):
    t = min(max(t, 0.0), 1.0)
    return 1 - (1 - t) ** 3


def phase(t, span):
    a, b = span
    return (t - a) / (b - a)


def state(t):
    """(outer_dy, outer_op, inner_dy, inner_op, ember_op) at time t (seconds)."""
    po, pi = phase(t, OUTER_T), phase(t, INNER_T)
    o_dy = OUTER_DY * (1 - ease_out_back(po))
    i_dy = INNER_DY * (1 - ease_out_back(pi))
    o_op = ease_out_cubic(po * 1.6)
    i_op = ease_out_cubic(pi * 1.6)
    if t < INNER_T[1]:
        e = 0.0
    else:
        k = (t - INNER_T[1]) / EMBER_PERIOD
        e = EMBER_MIN + (EMBER_MAX - EMBER_MIN) * (0.5 - 0.5 * math.cos(2 * math.pi * k))
        e *= ease_out_cubic((t - INNER_T[1]) / 0.6)
    return o_dy, o_op, i_dy, i_op, e


# ---- PNG pieces -------------------------------------------------------------
PIECE = 400  # pieces are rendered 400x400 (symbol box 256 -> 1.5625x); script scales them


def rsvg(svg_text, dst, w=None, h=None):
    cmd = ["rsvg-convert", "-o", dst]
    if w:
        cmd += ["-w", str(w)]
    if h:
        cmd += ["-h", str(h)]
    subprocess.run(cmd, input=svg_text.encode(), check=True)


def piece_svg(d, fill):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="{PIECE}" height="{PIECE}">'
            f'<path fill="{fill}" fill-rule="evenodd" d="{d}"/></svg>')


def solid_svg(fill, w=8, h=8, r=0):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
            f'<rect width="{w}" height="{h}" rx="{r}" fill="{fill}"/></svg>')


SCRIPT = r"""# Kiln GNU/Linux boot splash (%(scheme)s). Original artwork, MIT OR Apache-2.0.
# Generated by packaging/kilnlinux/plymouth/gen_plymouth.py - edit the generator, not this file.
# Paper arches slide up and settle, then the counter glows like an ember while booting.
# Set reduced_motion = 1 to show the arches in place with no pulse.

reduced_motion = %(reduced)d;

bg_r = %(bg_r).4f; bg_g = %(bg_g).4f; bg_b = %(bg_b).4f;
Window.SetBackgroundTopColor(bg_r, bg_g, bg_b);
Window.SetBackgroundBottomColor(bg_r, bg_g, bg_b);

screen_w = Window.GetWidth();
screen_h = Window.GetHeight();
# logo is 20 %% of the screen height (200 px on 1080p), never wider than half the screen
logo = Math.Int(Math.Min(screen_h * 0.20, screen_w * 0.5));
unit = screen_h / 1080;

outer_img = Image("outer.png").Scale(logo, logo);
inner_img = Image("inner.png").Scale(logo, logo);
ember_img = Image("ember.png").Scale(logo, logo);

logo_x = Window.GetX() + Math.Int((screen_w - logo) / 2);
logo_y = Window.GetY() + Math.Int(screen_h * 0.42 - logo / 2);

outer = Sprite(outer_img); outer.SetPosition(logo_x, logo_y, 10);
ember = Sprite(ember_img); ember.SetPosition(logo_x, logo_y, 11);
inner = Sprite(inner_img); inner.SetPosition(logo_x, logo_y, 12);

# progress bar: thin track with an eased fill
bar_w = Math.Int(logo * 1.2);
bar_h = Math.Max(2, Math.Int(3 * unit));
bar_x = Window.GetX() + Math.Int((screen_w - bar_w) / 2);
bar_y = logo_y + logo + Math.Int(48 * unit);
track = Sprite(Image("track.png").Scale(bar_w, bar_h)); track.SetPosition(bar_x, bar_y, 5);
fill_src = Image("fill.png");
fill = Sprite(fill_src.Scale(1, bar_h)); fill.SetPosition(bar_x, bar_y, 6);

global.frame = 0;
global.progress_target = 0;
global.progress_shown = 0;
global.fade = 1;
global.fading = 0;
global.last_fill = -1;

fun clamp01(v) { if (v < 0) return 0; if (v > 1) return 1; return v; }

fun ease_out_back(t) {
  t = clamp01(t);
  u = t - 1;
  return 1 + %(back3).4f * u * u * u + %(back1).4f * u * u;
}

fun ease_out_cubic(t) {
  t = clamp01(t);
  u = 1 - t;
  return 1 - u * u * u;
}

fun refresh_callback() {
  global.frame = global.frame + 1;
  t = global.frame / %(fps)d;
  if (reduced_motion) t = 100;

  po = (t - %(o0).3f) / %(od).3f;
  pi = (t - %(i0).3f) / %(id).3f;
  o_dy = %(ody)d * unit * (1 - ease_out_back(po));
  i_dy = %(idy)d * unit * (1 - ease_out_back(pi));
  o_op = ease_out_cubic(po * 1.6);
  i_op = ease_out_cubic(pi * 1.6);

  e = 0;
  if (t >= %(i1).3f && reduced_motion == 0) {
    k = (t - %(i1).3f) / %(period).3f;
    e = %(emin).3f + %(espan).3f * (0.5 - 0.5 * Math.Cos(2 * Math.Pi * k));
    e = e * ease_out_cubic((t - %(i1).3f) / 0.6);
  }

  if (global.fading) {
    global.fade = global.fade - 1 / (%(fade).3f * %(fps)d);
    if (global.fade < 0) global.fade = 0;
  }

  outer.SetY(logo_y + Math.Int(o_dy));
  inner.SetY(logo_y + Math.Int(i_dy));
  outer.SetOpacity(o_op * global.fade);
  inner.SetOpacity(i_op * global.fade);
  ember.SetOpacity(e * global.fade);

  # progress: ease toward the reported value, never backwards
  global.progress_shown = global.progress_shown + (global.progress_target - global.progress_shown) * 0.08;
  w = Math.Int(bar_w * global.progress_shown);
  if (w < 1) w = 1;
  if (w != global.last_fill) {
    fill.SetImage(fill_src.Scale(w, bar_h));
    global.last_fill = w;
  }
  bar_op = ease_out_cubic((t - 0.6) / 0.5) * global.fade;
  track.SetOpacity(bar_op);
  fill.SetOpacity(bar_op);
}
Plymouth.SetRefreshFunction(refresh_callback);

fun boot_progress_callback(duration, progress) {
  if (progress > global.progress_target) global.progress_target = progress;
}
Plymouth.SetBootProgressFunction(boot_progress_callback);

fun quit_callback() {
  global.fading = 1;
}
Plymouth.SetQuitFunction(quit_callback);

# ---- password prompt (encrypted disks) and messages ------------------------
prompt_sprite = Sprite(); prompt_sprite.SetPosition(0, 0, 20);
bullets_sprite = Sprite(); bullets_sprite.SetPosition(0, 0, 20);
message_sprite = Sprite(); message_sprite.SetPosition(0, 0, 20);

fun display_password_callback(prompt, bullets) {
  p = Image.Text(prompt, %(tx_r).4f, %(tx_g).4f, %(tx_b).4f);
  prompt_sprite.SetImage(p);
  prompt_sprite.SetPosition(Window.GetX() + Math.Int((screen_w - p.GetWidth()) / 2), bar_y + Math.Int(28 * unit), 20);
  prompt_sprite.SetOpacity(1);
  s = "";
  i = 0;
  while (i < bullets && i < 40) { s = s + "*"; i = i + 1; }
  if (s == "") s = " ";
  b = Image.Text(s, %(tx_r).4f, %(tx_g).4f, %(tx_b).4f);
  bullets_sprite.SetImage(b);
  bullets_sprite.SetPosition(Window.GetX() + Math.Int((screen_w - b.GetWidth()) / 2), bar_y + Math.Int(56 * unit), 20);
  bullets_sprite.SetOpacity(1);
}
Plymouth.SetDisplayPasswordFunction(display_password_callback);

fun display_normal_callback() {
  prompt_sprite.SetOpacity(0);
  bullets_sprite.SetOpacity(0);
}
Plymouth.SetDisplayNormalFunction(display_normal_callback);

fun message_callback(text) {
  m = Image.Text(text, %(tx_r).4f, %(tx_g).4f, %(tx_b).4f);
  message_sprite.SetImage(m);
  message_sprite.SetPosition(Window.GetX() + Math.Int((screen_w - m.GetWidth()) / 2), Window.GetY() + screen_h - Math.Int(64 * unit), 20);
}
Plymouth.SetMessageFunction(message_callback);
"""

PLYMOUTH_SCRIPT = """[Plymouth Theme]
Name=Kiln GNU/Linux{label}
Description=Paper arches settling into place, with an ember while booting.{desc}
ModuleName=script

[script]
ImageDir=/usr/share/plymouth/themes/{name}
ScriptFile=/usr/share/plymouth/themes/{name}/{name}.script
"""

PLYMOUTH_FRAMES = """[Plymouth Theme]
Name=Kiln GNU/Linux{label} (frames)
Description=Frame-sequence fallback for the Kiln splash (no script plugin needed).
ModuleName=two-step

[two-step]
ImageDir=/usr/share/plymouth/themes/{name}
HorizontalAlignment=.5
VerticalAlignment=.42
Transition=none
TransitionDuration=0.0
BackgroundStartColor=0x{bg}
BackgroundEndColor=0x{bg}
"""


def rgbf(hexc):
    h = hexc.lstrip("#")
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def frame_svg(t, scheme, size=200, w=None, h=None, fade=1.0, progress=None):
    """One frame of the motion as an SVG (logo box `size` px, optional full screen)."""
    bg, inner_c, track, _ = SCHEMES[scheme]
    o_dy, o_op, i_dy, i_op, e = state(t)
    s = size / 256
    unit = size / 200
    W, H = (w or size), (h or size)
    ox = (W - size) / 2
    oy = (H - size) / 2 if not h else H * 0.42 - size / 2
    body = [f'<rect width="{W}" height="{H}" fill="{bg}"/>' if h else ""]
    g = lambda dy, op, d, fill: (f'<path transform="translate({ox:.2f} {oy + dy * unit:.2f}) scale({s:.4f})" '
                                 f'fill="{fill}" fill-rule="evenodd" fill-opacity="{op * fade:.3f}" d="{d}"/>')
    body.append(g(o_dy, o_op, OUTER, TERRA))
    body.append(g(0, e, EMBER, TERRA))
    body.append(g(i_dy, i_op, INNER, inner_c))
    if progress is not None:
        bw, bh = size * 1.2, max(2, 3 * unit)
        bx, by = (W - bw) / 2, oy + size + 48 * unit
        bop = ease_out_cubic((t - 0.6) / 0.5) * fade
        body.append(f'<rect x="{bx:.1f}" y="{by:.1f}" width="{bw:.1f}" height="{bh:.1f}" fill="{track}" fill-opacity="{bop:.3f}"/>')
        body.append(f'<rect x="{bx:.1f}" y="{by:.1f}" width="{max(1, bw * progress):.1f}" height="{bh:.1f}" fill="{TERRA}" fill-opacity="{bop:.3f}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">'
            + "".join(body) + "</svg>")


def smil_svg(scheme):
    """Animated SVG preview (SMIL only, no script): intro once, then the ember loop."""
    bg, inner_c, track, _ = SCHEMES[scheme]
    W, H = 960, 540
    size = 200
    ox, oy = (W - size) / 2, H * 0.42 - size / 2
    s = size / 256
    # ease-out-back as a cubic Bezier approximation (x1 y1 x2 y2)
    back = "0.34 1.36 0.64 1"
    out = "0.33 1 0.68 1"

    def arch(d, fill, dy, t0, t1):
        dur = t1 - t0
        return (f'<g transform="translate({ox} {oy})"><g transform="translate(0 {dy})" opacity="0">'
                f'<animateTransform attributeName="transform" type="translate" from="0 {dy}" to="0 0" '
                f'begin="{t0}s" dur="{dur:.2f}s" fill="freeze" calcMode="spline" keyTimes="0;1" keySplines="{back}"/>'
                f'<animate attributeName="opacity" from="0" to="1" begin="{t0}s" dur="{dur / 1.6:.2f}s" fill="freeze" '
                f'calcMode="spline" keyTimes="0;1" keySplines="{out}"/>'
                f'<path transform="scale({s:.4f})" fill="{fill}" fill-rule="evenodd" d="{d}"/></g></g>')

    bw = size * 1.2
    bx, by = (W - bw) / 2, oy + size + 48
    i1 = INNER_T[1]
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">',
        f'<title>Kiln GNU/Linux boot animation preview ({scheme})</title>',
        '<!-- Original artwork, MIT OR Apache-2.0. Generated by glaze/packaging/kilnlinux/plymouth/gen_plymouth.py. '
        'Respects prefers-reduced-motion where the viewer supports CSS media queries in SVG. -->',
        '<style>@media (prefers-reduced-motion: reduce){.m{display:none}.still{display:inline}}.still{display:none}</style>',
        f'<rect width="{W}" height="{H}" fill="{bg}"/>',
        '<g class="m">',
        arch(OUTER, TERRA, OUTER_DY, OUTER_T[0], OUTER_T[1]),
        f'<g transform="translate({ox} {oy})"><path transform="scale({s:.4f})" fill="{TERRA}" d="{EMBER}" opacity="0">'
        f'<animate attributeName="opacity" values="{EMBER_MIN};{EMBER_MAX};{EMBER_MIN}" begin="{i1}s" '
        f'dur="{EMBER_PERIOD}s" repeatCount="indefinite" calcMode="spline" keyTimes="0;0.5;1" '
        f'keySplines="0.37 0 0.63 1;0.37 0 0.63 1"/></path></g>',
        arch(INNER, inner_c, INNER_DY, INNER_T[0], INNER_T[1]),
        f'<rect x="{bx}" y="{by}" width="{bw}" height="3" fill="{track}" opacity="0">'
        f'<animate attributeName="opacity" from="0" to="1" begin="0.6s" dur="0.5s" fill="freeze"/></rect>',
        f'<rect x="{bx}" y="{by}" width="1" height="3" fill="{TERRA}" opacity="0">'
        f'<animate attributeName="opacity" from="0" to="1" begin="0.6s" dur="0.5s" fill="freeze"/>'
        f'<animate attributeName="width" values="1;{bw * 0.35:.0f};{bw * 0.62:.0f};{bw * 0.9:.0f};{bw}" '
        f'keyTimes="0;0.25;0.5;0.8;1" begin="0.6s" dur="6s" fill="freeze"/></rect>',
        '</g>',
        f'<g class="still" transform="translate({ox} {oy}) scale({s:.4f})">'
        f'<path fill="{TERRA}" fill-rule="evenodd" d="{OUTER}"/><path fill="{inner_c}" fill-rule="evenodd" d="{INNER}"/></g>',
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


def b64(path):
    import base64
    with open(path, "rb") as fh:
        return base64.b64encode(fh.read()).decode()


def write(path, text):
    with open(path, "w") as fh:
        fh.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reduced-motion", action="store_true", help="bake reduced_motion = 1 into the scripts")
    args = ap.parse_args()
    if not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert is required")

    for scheme in ("dark", "light"):
        bg, inner_c, track, text = SCHEMES[scheme]
        name = "kiln" if scheme == "dark" else "kiln-light"
        d = os.path.join(HERE, name)
        os.makedirs(d, exist_ok=True)
        rsvg(piece_svg(OUTER, TERRA), os.path.join(d, "outer.png"))
        rsvg(piece_svg(INNER, inner_c), os.path.join(d, "inner.png"))
        rsvg(piece_svg(EMBER, TERRA), os.path.join(d, "ember.png"))
        rsvg(solid_svg(track), os.path.join(d, "track.png"))
        rsvg(solid_svg(TERRA), os.path.join(d, "fill.png"))
        br, bgg, bb = rgbf(bg)
        tr, tg, tb = rgbf(text)
        write(os.path.join(d, name + ".script"), SCRIPT % dict(
            scheme=scheme, reduced=1 if args.reduced_motion else 0, bg_r=br, bg_g=bgg, bg_b=bb,
            back3=BACK + 1, back1=BACK, fps=FPS, o0=OUTER_T[0], od=OUTER_T[1] - OUTER_T[0],
            i0=INNER_T[0], id=INNER_T[1] - INNER_T[0], i1=INNER_T[1], ody=OUTER_DY, idy=INNER_DY,
            period=EMBER_PERIOD, emin=EMBER_MIN, espan=EMBER_MAX - EMBER_MIN, fade=FADE_OUT,
            tx_r=tr, tx_g=tg, tx_b=tb))
        label = "" if scheme == "dark" else " (light)"
        write(os.path.join(d, name + ".plymouth"),
              PLYMOUTH_SCRIPT.format(name=name, label=label, desc="" if scheme == "dark" else " Light variant."))

        # two-step fallback: throbber = settled ember loop, animation = end fade-out.
        fname = "kiln-frames" if scheme == "dark" else "kiln-frames-light"
        fd = os.path.join(HERE, fname)
        os.makedirs(fd, exist_ok=True)
        for f_ in os.listdir(fd):
            if f_.endswith(".png"):
                os.remove(os.path.join(fd, f_))
        n_loop = int(EMBER_PERIOD * 15)  # 15 fps is plenty for a slow glow
        t_settled = INNER_T[1] + 0.6 + 10 * EMBER_PERIOD  # well into the loop (ember fully eased in)
        for i in range(n_loop):
            rsvg(frame_svg(t_settled + i * EMBER_PERIOD / n_loop, scheme), os.path.join(fd, f"throbber-{i:04d}.png"))
        n_end = 10
        for i in range(n_end):
            rsvg(frame_svg(t_settled, scheme, fade=1 - (i + 1) / n_end), os.path.join(fd, f"animation-{i:04d}.png"))
        rsvg(solid_svg(TERRA, 8, 8), os.path.join(fd, "progress-bar.png"))
        write(os.path.join(fd, fname + ".plymouth"),
              PLYMOUTH_FRAMES.format(name=fname, label=label, bg=bg.lstrip("#")))

        # SMIL preview in the brand folder
        if os.path.isdir(BRAND):
            write(os.path.join(BRAND, f"kiln-boot-animated-{scheme}.svg"), smil_svg(scheme))

        # review strip: sampled frames of the full-screen script motion (not installed)
        pv = os.path.join(HERE, "preview")
        os.makedirs(pv, exist_ok=True)
        times = [0.0, 0.12, 0.25, 0.4, 0.55, 0.7, 0.85, 1.0, 1.6, 2.4, 3.2]
        strip = []
        for k, t in enumerate(times):
            p = min(1.0, max(0.0, (t - 0.6) / 4))
            fp = os.path.join(pv, f"{scheme}-{k:02d}.png")
            rsvg(frame_svg(t, scheme, size=120, w=320, h=180, progress=p), fp)
            strip.append(fp)
        subprocess.run(["rsvg-convert", "-o", os.path.join(pv, f"strip-{scheme}.png")], check=True, input=(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{len(strip) * 330}" height="210">'
            + "".join(f'<image x="{i * 330}" y="0" width="320" height="180" href="data:image/png;base64,{b64(fp)}"/>'
                      f'<text x="{i * 330 + 4}" y="200" font-family="sans-serif" font-size="12">t={times[i]}s</text>'
                      for i, fp in enumerate(strip)) + "</svg>").encode())
    print("ok")


if __name__ == "__main__":
    main()
